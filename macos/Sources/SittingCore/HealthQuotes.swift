/// One short health fact. English ships in the binary; Vietnamese lives in
/// the downloadable language pack (`quote.<index>`), falling back to English
/// when the pack is missing. The first ~100 come from the Tauri app's
/// `facts.rs` (same product, same voice); the rest were written for the
/// macOS port in the same style: short, concrete numbers, cited when known.
public struct HealthQuote: Sendable, Equatable, Hashable {
    public let emoji: String
    public let en: String
    /// Position in `healthQuotes`, and the pack key suffix (`quote.<index>`).
    public let index: Int

    public init(_ emoji: String, _ en: String, index: Int) {
        self.emoji = emoji
        self.en = en
        self.index = index
    }

    public func text(in language: AppLanguage) -> String {
        LanguagePacks.string("quote.\(index)", english: en, for: language)
    }
}

